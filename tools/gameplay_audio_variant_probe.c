#include "nba_assets.h"
#include "nba_audio.h"
#include <stdio.h>
#include <string.h>

typedef struct { uint8_t command, srcn; uint16_t pitch; int16_t volume; } V;

static V expected(uint8_t c) {
    V v={c,0,0,0};
#define E(cmd,src,pit,vol) case cmd:v.srcn=src;v.pitch=pit;v.volume=vol;break
    switch(c) {
    E(0x08,0x00,0x0556,0x56); E(0x10,0x00,0x0524,0x56); E(0x18,0x00,0x0588,0x56);
    E(0x09,0x01,0x0556,0x28); E(0x11,0x01,0x0524,0x28); E(0x19,0x01,0x0588,0x28);
    E(0x0A,0x02,0x0556,0x1D); E(0x12,0x02,0x0524,0x1D); E(0x1A,0x02,0x0588,0x1D);
    E(0x0B,0x03,0x0556,0x2F); E(0x13,0x03,0x0524,0x2F); E(0x1B,0x03,0x0588,0x2F);
    E(0x0C,0x04,0x0800,0x1A); E(0x14,0x04,0x07CE,0x1A); E(0x1C,0x04,0x0832,0x1A);
    E(0x0D,0x05,0x0556,0x3D); E(0x15,0x05,0x0524,0x3D); E(0x1D,0x05,0x0588,0x3D);
    E(0x0E,0x06,0x0659,0x24); E(0x1E,0x06,0x068B,0x24);
    E(0x20,0x07,0x0400,0x39); E(0x28,0x07,0x03CE,0x39); E(0x30,0x07,0x0432,0x39);
    E(0x21,0x08,0x0400,0x21); E(0x29,0x08,0x03CE,0x21); E(0x31,0x08,0x0432,0x21);
    E(0x22,0x09,0x0400,0x21); E(0x2A,0x09,0x03CE,0x21); E(0x32,0x09,0x0432,0x21);
    E(0x23,0x0A,0x0800,0x0B); E(0x2B,0x0A,0x07CE,0x0B); E(0x33,0x0A,0x0832,0x0B);
    E(0x24,0x0B,0x0659,0x24); E(0x2C,0x0B,0x0627,0x24); E(0x34,0x0B,0x068B,0x24);
    default: break;
    }
#undef E
    return v;
}

static int family(NbaAudio *audio, uint16_t bit, const uint8_t *commands,
                  const uint16_t *seeds, unsigned count) {
    for(unsigned i=0;i<count;++i) {
        V want=expected(commands[i]);
        audio->gameplay_audio_rng_state=seeds[i];
        nba_audio_dispatch_gameplay_events(audio,0,0);
        nba_audio_dispatch_gameplay_events(audio,bit,0);
        if(audio->last_gameplay_command!=want.command ||
           audio->last_gameplay_srcn!=want.srcn ||
           audio->last_gameplay_pitch!=want.pitch ||
           audio->last_gameplay_volume!=want.volume) {
            fprintf(stderr,"bit=%04X index=%u got=%02X/%02X/%04X/%d want=%02X/%02X/%04X/%d\n",
                bit,i,audio->last_gameplay_command,audio->last_gameplay_srcn,
                audio->last_gameplay_pitch,audio->last_gameplay_volume,
                want.command,want.srcn,want.pitch,want.volume);
            return 1;
        }
    }
    return 0;
}

int main(int argc,char **argv) {
    static const uint16_t s3[]={0x0002,0x8001,0x0001,0x8000};
    static const uint16_t s15[]={0x0008,0x8003,0x0001,0x8002,0x0002,0x8001,0x0003,0x8000,
        0x0004,0x8007,0x0005,0x8006,0x0006,0x8005,0x0007,0x8004};
    static const uint16_t s7[]={0x0004,0x8003,0x0001,0x8002,0x0002,0x8001,0x0003,0x8000};
    static const uint8_t bounce[]={0x23,0x2B,0x33,0x23};
    static const uint8_t inner[]={0x09,0x0A,0x0B,0x11,0x12,0x13,0x19,0x1A,0x1B,0x0B,0x19,0x09,0x1A,0x13,0x0A,0x1B};
    static const uint8_t made[]={0x0C,0x14,0x1C,0x0C}, outer[]={0x08,0x10,0x18,0x08};
    static const uint8_t catchs[]={0x24,0x2C,0x34,0x24}, contact[]={0x0D,0x15,0x1D,0x0D};
    static const uint8_t shoe[]={0x0E,0x1E,0x1E,0x0E}, landing[]={0x20,0x28,0x30,0x20};
    static const uint8_t collision[]={0x21,0x29,0x31,0x22,0x2A,0x32,0x21,0x29};
    NbaAssetPack assets={0}; NbaAudio audio;
    if(argc!=2 || !nba_assets_load(&assets,argv[1])) return 2;
    nba_audio_init(&audio); nba_audio_set_host_playback_enabled(&audio,false);
    if(!nba_audio_start_gameplay(&audio,&assets)) return 3;
#define F(bit,cmd,seed) if(family(&audio,bit,cmd,seed,(unsigned)(sizeof(cmd)/sizeof(cmd[0]))))return 4
    F(0x0001,bounce,s3); F(0x0002,inner,s15); F(0x0004,made,s3);
    F(0x0008,outer,s3); F(0x0010,catchs,s3); F(0x0020,contact,s3);
    F(0x0040,shoe,s3); F(0x0080,collision,s7); F(0x0100,landing,s3);
    F(0x0200,collision,s7);
#undef F
    nba_audio_shutdown(&audio); nba_assets_free(&assets);
    puts("[PASS] 60 ROM command-table/RNG/DSP vectors, including both collision bits");
    return 0;
}
