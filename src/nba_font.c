const uint8_t *nba_font_get_glyph_8x8(char c) {
    unsigned char uc = (unsigned char)c;
    if (uc >= 128) uc = ' ';
    return g_font_8x8[uc];
}

int nba_font_get_text_width(const char *text, int scale) {
    if (!text) return 0;
    if (scale < 1) scale = 1;
    return (int)strlen(text) * NBA_FONT_CHAR_WIDTH * scale;
}

static void draw_glyph(uint32_t *pixels, int stride, int px, int py,
                       const uint8_t *glyph, uint32_t color, int scale) {
    for (int y = 0; y < 8; y++) {
        uint8_t row = glyph[y];
        for (int x = 0; x < 8; x++) {
            if (row & (0x80 >> x)) {
                for (int sy = 0; sy < scale; sy++) {
                    int dy = py + y * scale + sy;
                    if (dy < 0 || dy >= NBA_SNES_HEIGHT) continue;
                    for (int sx = 0; sx < scale; sx++) {
                        int dx = px + x * scale + sx;
                        if (dx < 0 || dx >= NBA_SNES_WIDTH) continue;
                        pixels[dy * stride + dx] = color;
                    }
                }
            }
        }
    }
}

void nba_font_render_text(uint32_t *pixels, int stride, int x, int y,
                          const char *text, uint32_t fg_color, uint32_t shadow_color,
                          int scale) {
    if (!pixels || !text) return;
    if (scale < 1) scale = 1;

    int cur_x = x;
    for (const char *p = text; *p; p++) {
        const uint8_t *glyph = nba_font_get_glyph_8x8(*p);

        /* Draw shadow if color != 0 */
        if (shadow_color != 0) {
            draw_glyph(pixels, stride, cur_x + scale, y + scale, glyph, shadow_color, scale);
        }

        /* Draw foreground */
        draw_glyph(pixels, stride, cur_x, y, glyph, fg_color, scale);

        cur_x += NBA_FONT_CHAR_WIDTH * scale;
    }
}

void nba_font_render_text_centered(uint32_t *pixels, int stride, int y,
                                   const char *text, uint32_t fg_color, uint32_t shadow_color,
                                   int scale) {
    if (!pixels || !text) return;
    int w = nba_font_get_text_width(text, scale);
    int x = (NBA_SNES_WIDTH - w) / 2;
    nba_font_render_text(pixels, stride, x, y, text, fg_color, shadow_color, scale);
}

