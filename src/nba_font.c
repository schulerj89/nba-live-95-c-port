void nba_font_render_licensed_by_nintendo(uint32_t *pixels, int stride, int x, int y,
                                         uint32_t fg_color, int scale) {
    if (!pixels) return;
    if (scale < 1) scale = 1;

    int width_bits = 128;
    int height_rows = 11;

    for (int r = 0; r < height_rows; r++) {
        for (int b = 0; b < 16; b++) {
            uint8_t byte_val = g_licensed_by_nintendo_bitmap[r][b];
            if (!byte_val) continue;

            for (int bit = 0; bit < 8; bit++) {
                if (byte_val & (0x80 >> bit)) {
                    int px_col = b * 8 + bit;
                    if (px_col >= width_bits) continue;

                    for (int sy = 0; sy < scale; sy++) {
                        int dy = y + r * scale + sy;
                        if (dy < 0 || dy >= NBA_SNES_HEIGHT) continue;

                        for (int sx = 0; sx < scale; sx++) {
                            int dx = x + px_col * scale + sx;
                            if (dx < 0 || dx >= NBA_SNES_WIDTH) continue;

                            pixels[dy * stride + dx] = fg_color;
                        }
                    }
                }
            }
        }
    }
}
